"""Build the Windows/LAN deployment package (T028).

    backend/.venv/bin/python deploy/build_package.py [--wheelhouse]

Writes backend/requirements.lock (runtime dependencies pinned to the versions the test suite ran with,
with Windows platform markers evaluated), builds the browser client (npm run build), and zips
backend/app, migrations, deploy/, Data/ (labeled SIMULATED datasets) and frontend/dist into
dist/pdm-<version>-windows.zip. With --wheelhouse it also downloads win_amd64 wheels for an offline
server (needs internet on the build machine).
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import subprocess
import sys
import zipfile
from importlib import metadata
from pathlib import Path

import tomllib
from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT = Path(__file__).resolve().parent.parent
BACKEND, FRONTEND, DIST = ROOT / "backend", ROOT / "frontend", ROOT / "dist"
PIP = (
    [sys.executable, "-m", "pip"]
    if importlib.util.find_spec("pip")
    else ["python3", "-m", "pip"]
)
WIN = {
    **default_environment(),
    "sys_platform": "win32",
    "platform_system": "Windows",
    "os_name": "nt",
}
INCLUDE = [
    "backend/app",
    "backend/alembic",
    "backend/alembic.ini",
    "backend/pyproject.toml",
    "backend/requirements.lock",
    "deploy",
    "Data",
    "frontend/dist",
    "README.md",
    "DECISIONS.md",
]
SKIP = re.compile(r"(__pycache__|\.pyc$|/var/|server\.log$|install\.log$|smoke/)")


def lock() -> list[str]:
    """Runtime dependency closure of backend/pyproject.toml for Windows, pinned to installed versions."""
    deps = tomllib.loads((BACKEND / "pyproject.toml").read_text(encoding="utf-8"))[
        "project"
    ]["dependencies"]
    seen: dict[str, str | None] = {}
    done: set[tuple[str, str]] = set()
    todo = [Requirement(r) for r in deps]
    while todo:
        req = todo.pop()
        name = re.sub(r"[-_.]+", "-", req.name).lower()
        for extra in sorted(req.extras) or [""]:
            if (name, extra) in done:
                continue
            done.add((name, extra))
            try:
                dist = metadata.distribution(name)
            except metadata.PackageNotFoundError:
                seen.setdefault(
                    name, None
                )  # Windows-only package not present on the build machine
                continue
            seen[name] = dist.version
            for r in dist.requires or []:
                sub = Requirement(r)
                m = sub.marker
                if m is None or (
                    m.evaluate({**WIN, "extra": extra})
                    and (extra or "extra" not in str(m))
                ):
                    todo.append(sub)
    return [f"{n}=={v}" if v else n for n, v in sorted(seen.items())]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--wheelhouse", action="store_true")
    ap.add_argument("--skip-frontend", action="store_true")
    args = ap.parse_args()
    reqs = lock()
    (BACKEND / "requirements.lock").write_text(
        "# Generated by deploy/build_package.py; runtime dependencies for Windows.\n"
        + "\n".join(reqs)
        + "\n",
        encoding="utf-8",
    )
    print(f"requirements.lock: {len(reqs)} packages")
    if not args.skip_frontend:
        subprocess.run(["npm", "run", "-s", "build"], cwd=FRONTEND, check=True)
    sys.path.insert(0, str(BACKEND))
    from app import __version__

    DIST.mkdir(exist_ok=True)
    out = DIST / f"pdm-{__version__}-windows.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for item in INCLUDE:
            p = ROOT / item
            files = (
                [p] if p.is_file() else sorted(f for f in p.rglob("*") if f.is_file())
            )
            for f in files:
                rel = f.relative_to(ROOT).as_posix()
                if not SKIP.search(rel):
                    z.write(f, f"pdm/{rel}")
        if args.wheelhouse:
            wh = DIST / "wheelhouse"
            subprocess.run(
                [
                    sys.executable,
                    "-m",
                    "pip",
                    "download",
                    "-r",
                    str(BACKEND / "requirements.lock"),
                    "-d",
                    str(wh),
                    "--only-binary=:all:",
                    "--platform",
                    "win_amd64",
                    "--python-version",
                    "3.12",
                    "--implementation",
                    "cp",
                ],
                check=True,
            )
            for f in sorted(wh.iterdir()):
                z.write(f, f"pdm/wheelhouse/{f.name}")
    print(f"{out} ({out.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
