"""Build the offline one-click Windows bundle (no internet needed on the server).

    backend/.venv/bin/python deploy/build_offline.py --python-nupkg python.3.12.10.nupkg

Layout of dist/pdm-<version>-offline-win64.zip:
    install.cmd / uninstall.cmd      double-click entry points
    verify.cmd                       test run on SIMULATED demo data (flow check + demo server)
    setup/                           PowerShell installer (uses the existing PostgreSQL 17)
    runtime/python/                  Windows CPython 3.12 (NuGet "python" package) with every runtime
                                     dependency pre-installed in Lib/site-packages (win_amd64 wheels)
    pdm/                             backend, migrations, built browser client, deploy scripts, SIMULATED data
    DEPLOY_GUIDE.md                  bilingual guide
The build machine needs internet for pip (PyPI) once; the target server needs none.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "deploy"))
from build_package import INCLUDE, PIP, SKIP, lock


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--python-nupkg", type=Path, required=True)
    ap.add_argument("--work", type=Path, default=ROOT / "dist" / "offline")
    args = ap.parse_args()
    sys.path.insert(0, str(ROOT / "backend"))
    from app import __version__

    reqs = lock()
    (ROOT / "backend" / "requirements.lock").write_text(
        "# Generated by deploy/build_package.py; runtime dependencies for Windows.\n"
        + "\n".join(reqs)
        + "\n",
        encoding="utf-8",
    )
    subprocess.run(["npm", "run", "-s", "build"], cwd=ROOT / "frontend", check=True)
    shutil.rmtree(args.work, ignore_errors=True)
    py = args.work / "runtime" / "python"
    with zipfile.ZipFile(args.python_nupkg) as z:
        for n in z.namelist():
            if n.startswith("tools/") and not n.endswith("/"):
                out = py / n.removeprefix("tools/")
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_bytes(z.read(n))
    site = py / "Lib" / "site-packages"
    subprocess.run(
        [
            *PIP,
            "install",
            "-q",
            "--target",
            str(site),
            "--platform",
            "win_amd64",
            "--python-version",
            "3.12",
            "--implementation",
            "cp",
            "--only-binary=:all:",
            "--no-compile",
            "--no-deps",  # the lock already resolved Windows markers
            "-r",
            str(ROOT / "backend" / "requirements.lock"),
        ],
        check=True,
    )
    for stray in site.glob("*.whl"):
        stray.unlink()
    for item in INCLUDE:
        p = ROOT / item
        for f in [p] if p.is_file() else sorted(x for x in p.rglob("*") if x.is_file()):
            rel = f.relative_to(ROOT).as_posix()
            if not SKIP.search(rel):
                dst = args.work / "pdm" / rel
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(f, dst)
    off = ROOT / "deploy" / "offline"
    (args.work / "setup").mkdir()
    for n in ["offline_install.ps1", "offline_uninstall.ps1"]:
        shutil.copy2(off / n, args.work / "setup" / n)
    for n in ["install.cmd", "uninstall.cmd", "verify.cmd"]:
        shutil.copy2(off / n, args.work / n)
    shutil.copy2(off / "DEPLOY_GUIDE.md", args.work / "DEPLOY_GUIDE.md")
    out = ROOT / "dist" / f"pdm-{__version__}-offline-win64.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for f in sorted(x for x in args.work.rglob("*") if x.is_file()):
            z.write(f, f"pdm-offline/{f.relative_to(args.work).as_posix()}")
    print(f"{out} ({out.stat().st_size / 1e6:.0f} MB, {len(reqs)} packages)")


if __name__ == "__main__":
    main()
